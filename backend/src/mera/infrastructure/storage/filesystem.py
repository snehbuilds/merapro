"""Filesystem ``ObjectStore`` on a mounted volume (docs/01 §5.5).

Keys are generated by Mera (``ws/<workspace>/<asset>.<ext>``), never taken from a request,
and are still validated here: a key that could climb out of the root is refused, not
normalised. Writes go to a temporary file and are renamed into place, so a reader never
sees half an image.

``presigned_url`` signs ``key`` and an expiry with an HMAC key derived from the service
secret. The API's public file route checks the signature in constant time and serves the
bytes until the expiry; nothing else about the store is reachable without a session.
"""

from __future__ import annotations

import asyncio
import hashlib
import hmac
import os
import re
import tempfile
import time
from datetime import timedelta
from pathlib import Path
from urllib.parse import quote

from mera.domain.ports.object_store import ObjectNotFound, StoredObject

_KEY = re.compile(r"^[a-z0-9][a-z0-9_-]*(/[a-z0-9][a-z0-9_.-]*){1,4}$")
MAX_TTL = timedelta(hours=24)
_HEX64 = re.compile(r"[0-9a-f]{64}")


class InvalidKey(ValueError):
    pass


def check_key(key: str) -> str:
    if len(key) > 200 or not _KEY.fullmatch(key) or ".." in key:
        raise InvalidKey("invalid object key")
    return key


class FilesystemObjectStore:
    def __init__(self, root: Path, *, signing_key: bytes, public_base_url: str) -> None:
        self._root = root.resolve()
        self._signing_key = signing_key
        self._base = public_base_url.rstrip("/")

    def _path(self, key: str) -> Path:
        path = (self._root / check_key(key)).resolve()
        if self._root not in path.parents:
            raise InvalidKey("invalid object key")
        return path

    async def check_ready(self) -> dict[str, str | int]:
        """Fail startup when the configured mount is absent or not writable.

        The device and inode are logged by API and worker so operators can compare the
        effective mounts without exposing any object names.
        """

        def check() -> dict[str, str | int]:
            self._root.mkdir(parents=True, exist_ok=True)
            if not self._root.is_dir():
                raise NotADirectoryError(str(self._root))
            fd, probe = tempfile.mkstemp(dir=self._root, prefix=".mera-storage-probe-")
            try:
                os.write(fd, b"ready")
                os.fsync(fd)
            finally:
                os.close(fd)
                Path(probe).unlink(missing_ok=True)
            stat = self._root.stat()
            return {"root": str(self._root), "device": stat.st_dev, "inode": stat.st_ino}

        return await asyncio.to_thread(check)

    async def put(self, key: str, data: bytes, content_type: str) -> StoredObject:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".tmp-")
            try:
                with os.fdopen(fd, "wb") as f:
                    f.write(data)
                    f.flush()
                    os.fsync(f.fileno())
                os.replace(tmp, path)
            except BaseException:
                Path(tmp).unlink(missing_ok=True)
                raise

        await asyncio.to_thread(write)
        return StoredObject(key=key, byte_size=len(data))

    async def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return await asyncio.to_thread(path.read_bytes)
        except FileNotFoundError as exc:
            raise ObjectNotFound(key) from exc

    async def delete(self, key: str) -> None:
        path = self._path(key)
        await asyncio.to_thread(path.unlink, missing_ok=True)

    # ------------------------------------------------------------------ signed URLs

    def _signature(self, key: str, expires: int) -> str:
        msg = f"mera-media-file-v1\n{key}\n{expires}".encode()
        return hmac.new(self._signing_key, msg, hashlib.sha256).hexdigest()

    async def presigned_url(self, key: str, ttl: timedelta) -> str:
        check_key(key)
        expires = int(time.time() + min(ttl, MAX_TTL).total_seconds())
        sig = self._signature(key, expires)
        return f"{self._base}/api/v1/media-files/{quote(key)}?exp={expires}&sig={sig}"

    def verify(self, key: str, expires: int, signature: str) -> bool:
        try:
            check_key(key)
        except InvalidKey:
            return False
        if expires < time.time() or expires > time.time() + MAX_TTL.total_seconds() + 60:
            return False
        if not _HEX64.fullmatch(signature):
            return False  # also keeps non-ASCII input away from compare_digest
        return hmac.compare_digest(self._signature(key, expires), signature)


def signing_key_from_secret(secret: str) -> bytes:
    """A key for media URLs only, so a leaked URL signature says nothing about the secret."""
    return hmac.new(secret.encode(), b"mera-media-url-v1", hashlib.sha256).digest()
